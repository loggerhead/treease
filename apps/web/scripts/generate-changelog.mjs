import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repoDir = path.resolve(webDir, '../..');
const outputPath = path.join(webDir, 'src/lib/content/changelog.generated.ts');
const feedPath = path.join(webDir, 'static/changelog.xml');
const metadataPath = path.join(webDir, 'src/lib/content/changelog.generated.meta.json');
const schemaPath = path.join(webDir, 'scripts/changelog.schema.json');
const generatorVersion = 3;
const tutorialSourcePath = path.join(webDir, 'src/lib/content/tutorials/index.ts');
const model = process.env.TREEASE_CODEX_MODEL;
const tempDir = mkdtempSync(path.join(tmpdir(), 'treease-changelog-'));
const responsePath = path.join(tempDir, 'response.json');

try {
  const commits = execFileSync('git', ['log', '--date=short', '--pretty=format:%h%x09%ad%x09%s'], { cwd: repoDir, encoding: 'utf8' });
  const commitRows = commits.split('\n').map((row, index) => {
    const [hash, date, ...subjectParts] = row.split('\t');
    return { index, hash, date, subject: subjectParts.join('\t') };
  });
  const tutorialSource = readFileSync(tutorialSourcePath, 'utf8');
  const tutorialCatalog = [...tutorialSource.matchAll(/slug:\s*'([^']+)'[\s\S]*?title:\s*'([^']+)'/g)].map(([, slug, title]) => ({ slug, title }));
  const inputCommitHashes = commitRows.map(({ hash }) => hash);
  let cachedMetadata = null;
  if (existsSync(metadataPath)) {
    try {
      cachedMetadata = JSON.parse(readFileSync(metadataPath, 'utf8'));
    } catch {
      cachedMetadata = null;
    }
  }
  const cacheIsValid = cachedMetadata?.generatorVersion === generatorVersion
    && Array.isArray(cachedMetadata.chunks)
    && JSON.stringify(cachedMetadata.inputCommitHashes) === JSON.stringify(inputCommitHashes)
    && existsSync(outputPath)
    && existsSync(feedPath);
  if (cacheIsValid) {
    if (cachedMetadata.slugFormat !== 'iso-date') {
      const entries = cachedMetadata.chunks.map(({ entry }) => ({ ...entry, slug: entry.isoDate }));
      const source = `// Generated by apps/web/scripts/generate-changelog.mjs. Do not edit by hand.\nimport type { ChangelogEntry } from './changelog';\n\nexport const generatedChangelog = ${JSON.stringify(entries, null, 2)} satisfies readonly ChangelogEntry[];\n`;
      writeFileSync(outputPath, source);
      const escapeXml = (value) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
      const items = entries.map((entry) => `\n    <item><title>${escapeXml(entry.title)}</title><link>https://treease.com/changelog/${escapeXml(entry.slug)}</link><guid isPermaLink="false">treease-${escapeXml(entry.slug)}</guid><pubDate>${new Date(`${entry.isoDate}T00:00:00Z`).toUTCString()}</pubDate><description>${escapeXml(entry.summary)}</description></item>`).join('');
      writeFileSync(feedPath, `<?xml version="1.0" encoding="UTF-8" ?><rss version="2.0"><channel><title>Treease Changelog</title><link>https://treease.com/changelog</link><description>New updates and product improvements in Treease.</description>${items}\n  </channel></rss>\n`);
      cachedMetadata.slugFormat = 'iso-date';
      cachedMetadata.chunks = cachedMetadata.chunks.map((chunk, index) => ({ ...chunk, entry: entries[index] }));
      writeFileSync(metadataPath, `${JSON.stringify(cachedMetadata, null, 2)}\n`);
      console.log(`Migrated ${entries.length} generated entries to date-based slugs.`);
    }
    console.log(`Changelog inputs unchanged; reused ${cachedMetadata.chunks.length} generated entries.`);
  } else {
  const commitPrompt = commitRows
    .map(({ index, date, subject }) => `Commit ${index} | ${date} | ${subject || '(no subject)'}`)
    .join('\n');
  const tutorialPrompt = tutorialCatalog.map(({ slug, title }) => `- /tutorial/${slug} | ${title}`).join('\n');
  const prompt = `You are preparing product changelog entries for Treease, a structured-text graph editor. Write every changelog entry in English.\n\nClassify the complete newest-first commit history below. A changelog chunk is a coherent user-facing feature or bugfix theme, and the same theme across multiple dates MUST be combined into one chunk. Date is an anti-splitting boundary: all user-facing commits from one date MUST belong to the same chunk, even when that date contains many unrelated topics. Therefore a chunk may contain multiple topics when required to keep a date intact, and related topics from adjacent dates must be merged.\n\nKeep only user-visible changes: features, bug fixes, performance improvements, reliability improvements, meaningful UX changes, and shipped product behavior. Put documentation-only, CI-only, tests-only, release/versioning-only, dependency-only, internal refactors, and other user-invisible commits in ignoredCommitIndexes. If a commit mixes internal work with a user-visible result, keep it in the relevant chunk. Every input commit index must appear exactly once either in a chunk's commitIndexes or in ignoredCommitIndexes. No index may appear in more than one place.\n\nAvailable tutorials for internal linking (use the exact href and title):\n${tutorialPrompt}\n\n${commitPrompt}\n\nReturn JSON matching the supplied schema. Use zero-based chunkIndex values in newest-first order. Each chunk must have at least one commit index. Write one complete English changelog entry per chunk, covering all user-visible features and bug fixes represented by its commits. Use 1-3 sections per chunk when useful; do not leave sections empty when the chunk contains multiple meaningful changes. If a chunk's update is directly related to one or more available tutorials, add those exact tutorial links to tutorialLinks; otherwise return an empty tutorialLinks array. Use the date of the newest included commit as date and isoDate. Set featured=true only on chunk 0 and false on all others. Do not mention commit hashes, internal implementation details, or unreleased work.`;
  const codexArgs = ['exec', '--ephemeral', '--sandbox', 'read-only', '--skip-git-repo-check', '--output-schema', schemaPath, '--output-last-message', responsePath];
  if (model) codexArgs.push('-m', model);
  codexArgs.push('-C', repoDir, prompt);
  execFileSync('codex', codexArgs, { stdio: 'inherit' });
  const payload = JSON.parse(readFileSync(responsePath, 'utf8'));
  const chunks = payload.chunks;
  const ignoredCommitIndexes = payload.ignoredCommitIndexes;
  if (!Array.isArray(chunks) || chunks.length === 0) throw new Error('Codex returned no changelog chunks');
  if (!Array.isArray(ignoredCommitIndexes)) throw new Error('Codex returned no ignored commit indexes');
  for (const [chunkIndex, chunk] of chunks.entries()) {
    if (chunk.chunkIndex !== chunkIndex) throw new Error(`Expected chunkIndex ${chunkIndex}, received ${chunk.chunkIndex}`);
  }
  if (chunks[0]?.entry.featured !== true || chunks.some((chunk, index) => index > 0 && chunk.entry.featured !== false)) throw new Error('Only the newest changelog entry may be featured');
  const assignedIndexes = chunks.flatMap((chunk) => chunk.commitIndexes);
  const allIndexes = [...assignedIndexes, ...ignoredCommitIndexes];
  const expectedIndexes = commitRows.map(({ index }) => index);
  if (new Set(allIndexes).size !== allIndexes.length || allIndexes.some((index) => !expectedIndexes.includes(index)) || allIndexes.length !== expectedIndexes.length) {
    throw new Error('Every commit index must be assigned exactly once');
  }
  const chunkByIndex = new Map(assignedIndexes.map((index, chunkIndex) => [index, chunks.findIndex((chunk) => chunk.commitIndexes.includes(index))]));
  for (const date of new Set(commitRows.map((commit) => commit.date))) {
    const dateChunkIndexes = new Set(commitRows.filter((commit) => commit.date === date && chunkByIndex.has(commit.index)).map((commit) => chunkByIndex.get(commit.index)));
    if (dateChunkIndexes.size > 1) throw new Error(`Commits from ${date} were split across changelog chunks`);
  }
  const entries = chunks.map((chunk) => ({
    ...chunk.entry,
    slug: chunk.entry.isoDate,
  }));
  const source = `// Generated by apps/web/scripts/generate-changelog.mjs. Do not edit by hand.\nimport type { ChangelogEntry } from './changelog';\n\nexport const generatedChangelog = ${JSON.stringify(entries, null, 2)} satisfies readonly ChangelogEntry[];\n`;
  writeFileSync(outputPath, source);
  const escapeXml = (value) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
  const items = entries.map((entry) => `\n    <item><title>${escapeXml(entry.title)}</title><link>https://treease.com/changelog/${escapeXml(entry.slug)}</link><guid isPermaLink="false">treease-${escapeXml(entry.slug)}</guid><pubDate>${new Date(`${entry.isoDate}T00:00:00Z`).toUTCString()}</pubDate><description>${escapeXml(entry.summary)}</description></item>`).join('');
  writeFileSync(feedPath, `<?xml version="1.0" encoding="UTF-8" ?><rss version="2.0"><channel><title>Treease Changelog</title><link>https://treease.com/changelog</link><description>New updates and product improvements in Treease.</description>${items}\n  </channel></rss>\n`);
  writeFileSync(metadataPath, `${JSON.stringify({
    generatorVersion,
    slugFormat: 'iso-date',
    inputCommitHashes,
    chunks: chunks.map((chunk, index) => ({
      commitHashes: chunk.commitIndexes.map((index) => commitRows[index].hash),
      entry: entries[index],
    })),
    ignoredCommitHashes: ignoredCommitIndexes.map((index) => commitRows[index].hash),
  }, null, 2)}\n`);
  console.log(`Wrote ${entries.length} changelog entries to ${path.relative(repoDir, outputPath)}`);
  }
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
